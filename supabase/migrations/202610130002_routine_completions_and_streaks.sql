-- Per-step daily routine tracking and server-side streak recalculation.
-- Existing check_ins rows and streak history are retained.

create table if not exists public.routine_step_completions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  user_product_id uuid not null references public.user_products(id) on delete cascade,
  completion_date date not null,
  routine_slot text not null check (routine_slot in ('AM', 'PM')),
  completed_at timestamptz not null default now(),
  unique (user_id, user_product_id, completion_date)
);

alter table public.routine_step_completions enable row level security;
drop policy if exists glowtrack_routine_completion_owner on public.routine_step_completions;
create policy glowtrack_routine_completion_owner
  on public.routine_step_completions for all to authenticated
  using (
    auth.uid() = user_id and exists (
      select 1 from public.user_products product
      where product.id = user_product_id and product.user_id = auth.uid()
    )
  )
  with check (
    auth.uid() = user_id and exists (
      select 1 from public.user_products product
      where product.id = user_product_id and product.user_id = auth.uid()
    )
  );
grant select, insert, update, delete on public.routine_step_completions to authenticated;
grant usage, select on sequence public.routine_step_completions_id_seq to authenticated;

create or replace function public.recalculate_glowtrack_streak(p_today date)
returns integer
language plpgsql
security invoker
set search_path = public
as $$
declare
  owner_id uuid := auth.uid();
  latest_day date;
  prior_day date;
  day_row record;
  run_count integer := 0;
  current_count integer := 0;
  longest_count integer := 0;
begin
  if owner_id is null then raise exception 'Authentication required'; end if;

  select max(check_in_date) into latest_day
  from public.check_ins
  where user_id = owner_id and am_completed and pm_completed and check_in_date <= p_today
    and exists (
      select 1 from public.user_products product
      where product.user_id = owner_id
        and (product.source is null or product.source in ('manual', 'recommendation_accepted'))
    );

  if latest_day is null or p_today - latest_day >= 3 then
    current_count := 0;
  else
    for day_row in
      select check_in_date from public.check_ins
      where user_id = owner_id and am_completed and pm_completed and check_in_date <= latest_day
        and exists (
          select 1 from public.user_products product
          where product.user_id = owner_id
            and (product.source is null or product.source in ('manual', 'recommendation_accepted'))
        )
      order by check_in_date desc
    loop
      if prior_day is null or prior_day - day_row.check_in_date <= 2 then
        run_count := run_count + 1;
      else
        exit;
      end if;
      prior_day := day_row.check_in_date;
    end loop;
    current_count := run_count;
  end if;

  insert into public.streaks (user_id, current_streak, longest_streak, last_check_in_date)
  values (owner_id, current_count, current_count, latest_day)
  on conflict (user_id) do update set
    current_streak = excluded.current_streak,
    longest_streak = greatest(public.streaks.longest_streak, excluded.longest_streak),
    last_check_in_date = excluded.last_check_in_date;
  return current_count;
end;
$$;

create or replace function public.set_routine_step_completion(
  p_user_product_id uuid,
  p_completion_date date,
  p_completed boolean
)
returns integer
language plpgsql
security invoker
set search_path = public
as $$
declare
  owner_id uuid := auth.uid();
  step_slot text;
  am_total integer;
  pm_total integer;
  am_done_count integer;
  pm_done_count integer;
  has_steps boolean;
  am_done boolean;
  pm_done boolean;
  current_streak integer;
begin
  if owner_id is null then raise exception 'Authentication required'; end if;
  select routine_slot into step_slot
  from public.user_products
  where id = p_user_product_id and user_id = owner_id
    and (source is null or source in ('manual', 'recommendation_accepted'));
  if step_slot is null then raise exception 'Routine step not found'; end if;

  if p_completed then
    insert into public.routine_step_completions(user_id, user_product_id, completion_date, routine_slot)
    values(owner_id, p_user_product_id, p_completion_date, step_slot)
    on conflict (user_id, user_product_id, completion_date) do nothing;
  else
    delete from public.routine_step_completions
    where user_id = owner_id and user_product_id = p_user_product_id and completion_date = p_completion_date;
  end if;

  select count(*) filter (where routine_slot = 'AM'),
         count(*) filter (where routine_slot = 'PM')
    into am_total, pm_total
  from public.user_products
  where user_id = owner_id and (source is null or source in ('manual', 'recommendation_accepted'));
  has_steps := am_total + pm_total > 0;

  select count(*) filter (where completion.routine_slot = 'AM'),
         count(*) filter (where completion.routine_slot = 'PM')
    into am_done_count, pm_done_count
  from public.routine_step_completions completion
  join public.user_products product on product.id = completion.user_product_id
  where completion.user_id = owner_id and completion.completion_date = p_completion_date
    and (product.source is null or product.source in ('manual', 'recommendation_accepted'));

  am_done := has_steps and (am_total = 0 or am_done_count = am_total);
  pm_done := has_steps and (pm_total = 0 or pm_done_count = pm_total);
  insert into public.check_ins(user_id, check_in_date, am_completed, pm_completed)
  values(owner_id, p_completion_date, am_done, pm_done)
  on conflict (user_id, check_in_date) do update set
    am_completed = excluded.am_completed,
    pm_completed = excluded.pm_completed;

  current_streak := public.recalculate_glowtrack_streak(p_completion_date);
  return current_streak;
end;
$$;

revoke all on function public.recalculate_glowtrack_streak(date) from public;
grant execute on function public.recalculate_glowtrack_streak(date) to authenticated;
revoke all on function public.set_routine_step_completion(uuid, date, boolean) from public;
grant execute on function public.set_routine_step_completion(uuid, date, boolean) to authenticated;
